export function determineArchetype(scores: Record<string, number>): { primary: Archetype; secondary: Archetype | null } {
  const archetypeScores: Record<string, number> = {};
  for (const [key, value] of Object.entries(scores)) {
    if (key.startsWith("archetype_")) {
      archetypeScores[key] = value;
    }
  }
  
  // If no archetype scores, determine from other scores
  if (Object.keys(archetypeScores).length === 0 || Math.max(...Object.values(archetypeScores)) === 0) {
    // Heuristic assignment
    const e = scores.energy || 0;
    const sc = scores.selfContact || 0;
    const c = scores.clarity || 0;
    const st = scores.selfTrust || 0;
    const r = scores.readiness || 0;
    const res = scores.resources || 0;
    const p = scores.purpose || 0;
    const stuck = scores.stuckness || 0;

    if (r >= 4 && e >= 3) archetypeScores["archetype_reborn"] = 5;
    else if (c >= 3 && p >= 3) archetypeScores["archetype_seeker"] = 5;
    else if (res >= 3 && st >= 3) archetypeScores["archetype_keeper"] = 5;
    else if (p >= 4) archetypeScores["archetype_creator"] = 5;
    else if (sc >= 3) archetypeScores["archetype_guide"] = 5;
    else archetypeScores["archetype_alchemist"] = 5;
  }

  const sorted = Object.entries(archetypeScores).sort((a, b) => b[1] - a[1]);
  const primaryKey = sorted[0]?.[0] || "archetype_reborn";
  const secondaryKey = sorted[1]?.[1] > 0 ? sorted[1]?.[0] : null;

  return {
    primary: archetypes[primaryKey] || archetypes["archetype_reborn"],
    secondary: secondaryKey ? archetypes[secondaryKey] || null : null,
  };
}
